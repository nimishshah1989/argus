/** The facts a Why-Why sheet prints: the breakdown, the five whys and the record's author and day. */
export interface WhyWhyPdfInput {
  tenant: { name: string; language: string; timeZone: string };
  ticket: {
    ref: string;
    problem: string;
    machine: { code: string | null; category: string | null; cell: string | null };
  };
  /** The breakdown report's plant date, or the closed ticket's own day when it has no report. */
  date: string;
  hours: number;
  record: WhyWhyPayload;
  /** The author's coded name, never a real name (R2: a person is an id). */
  author: string;
  generatedAt: Date;
}

/** A plant date as the platform prints it: DD-MM-YYYY. */
export function dmy(date: string): string {
  const [year, month, day] = date.split('-');
  return year && month && day ? `${day}-${month}-${year}` : date;
}

function field(label: string, value: string): string {
  return `<div class="field"><div class="label">${esc(label)}</div><div class="value">${esc(value)}</div></div>`;
}

function whyRow(why: string, index: number): string {
  return `<li><div class="why-label">Why ${index + 1}</div><div class="why-text">${esc(
    why.trim() || '—',
  )}</div></li>`;
}

const SHEET_STYLES = `
.facts { display: grid; grid-template-columns: repeat(2, minmax(30mm, auto)); gap: 3mm 8mm; }
.field .label, .why-label { font-size: 7.5pt; letter-spacing: 0.08em; text-transform: uppercase; color: #6b7280; }
.field .value { font-size: 11pt; }
.whys { margin: 0; padding: 0; list-style: none; }
.whys li { display: flex; gap: 4mm; padding: 2mm 0; border-bottom: 1px solid #f1f2f4; }
.why-label { width: 18mm; flex: none; }
.why-text { font-size: 11pt; }
.conclusion { font-size: 12pt; margin: 0; }
`;

/** The server-rendered Why-Why sheet: one closed breakdown, its five whys and its conclusion. */
export function renderWhyWhyHtml(input: WhyWhyPdfInput): string {
  const { ticket, record } = input;
  const facts = [
    field('Machine', machineLabel(ticket.machine)),
    field('Date', dmy(input.date)),
    field('Down (Hrs)', input.hours.toFixed(2)),
    field('Problem', ticket.problem),
  ].join('');
  return `<!doctype html>
<html lang="${esc(input.tenant.language)}">
<head>
  <meta charset="utf-8" />
  <title>Why-Why ${esc(ticket.ref)} ${esc(dmy(input.date))}</title>
  <style>${STYLES}${SHEET_STYLES}</style>
</head>
<body>
<header>
  <div class="masthead">
    <div class="company">${esc(input.tenant.name)}</div>
    <h1>Why-Why analysis</h1>
    <div class="who">Ticket ${esc(ticket.ref)} · ${esc(machineLabel(ticket.machine))}</div>
  </div>
</header>
<section><h2>Breakdown</h2><div class="facts">${facts}</div></section>
<section><h2>The five whys</h2><ol class="whys">${record.whys
    .map((why, index) => whyRow(why, index))
    .join('')}</ol></section>
<section><h2>Conclusion</h2><p class="conclusion">${esc(record.conclusion)}</p></section>
<footer>Completed by ${esc(input.author)} on ${esc(dmy(record.completedDate))} · Generated by UPTIMO on ${esc(
    formatDateTime(input.generatedAt, input.tenant.timeZone),
  )}</footer>
</body>
</html>`;
}

/** `WhyWhy_<machine>_<date>.pdf`, the name the platform used. */
export function whyWhyPdfName(machine: string, date: string): string {
  return `WhyWhy_${machine}_${dmy(date)}.pdf`.replace(/[^A-Za-z0-9._-]+/g, '_');
}

type PdfState =
  | { state: 'missing' }
  | { state: 'not-breakdown' }
  | { state: 'no-record' }
  | { state: 'ok'; input: WhyWhyPdfInput; fileName: string };

type Tenant = Awaited<ReturnType<typeof tenantInfo>>;

function machineOf(row: Record<string, unknown>): WhyWhyPdfInput['ticket']['machine'] {
  return {
    code: (row.machine_code as string | null) ?? null,
    category: (row.machine_category as string | null) ?? null,
    cell: (row.machine_cell as string | null) ?? null,
  };
}

/** The report's own date, or the closed ticket's plant day when it has no report. */
async function dateOf(
  client: PoolClient,
  tenantId: string,
  report: Awaited<ReturnType<typeof loadReport>>,
  row: Record<string, unknown>,
): Promise<string> {
  if (report) return report.date;
  const closedAt = row.closed_at;
  const at = closedAt ? new Date(closedAt as string) : new Date(row.reported_at as string);
  return plantToday(client, tenantId, at);
}

/** The report's downtime, or the closed ticket's recorded minutes when it has no report. */
function minutesOf(
  report: Awaited<ReturnType<typeof loadReport>>,
  row: Record<string, unknown>,
): number {
  if (report) return report.downtimeMin;
  const minutes = row.downtime_min;
  return typeof minutes === 'number' ? minutes : 0;
}

/**
 * One ticket's sheet facts, inside the tenant transaction. Missing, not a closed breakdown and no saved record
 * are told apart so the route can answer 404, 409 not-a-breakdown and 409 no record.
 */
async function sheetOf(client: PoolClient, tenantId: string, ticketId: string): Promise<PdfState> {
  const rows = await pdfTicketRow(client, tenantId, ticketId);
  if (rows.length === 0) return { state: 'missing' };
  const row = (await withMachines(client, tenantId, rows))[0] as Record<string, unknown>;
  if (row.kind !== 'stopped' || row.status !== 'closed') return { state: 'not-breakdown' };
  const record = await loadWhyWhy(client, tenantId, ticketId);
  if (!record) return { state: 'no-record' };
  const report = await loadReport(client, ticketId);
  const tenant: Tenant = await tenantInfo(client, tenantId);
  const date = await dateOf(client, tenantId, report, row);
  const machine = machineOf(row);
  const ref = row.ref as string;
  return {
    state: 'ok',
    input: {
      tenant: {
        name: tenant.name as string,
        language: tenant.language as string,
        timeZone: tenant.time_zone as string,
      },
      ticket: { ref, problem: row.problem as string, machine },
      date,
      hours: minutesOf(report, row) / 60,
      record,
      author: personCode(record.completedBy),
      generatedAt: new Date(),
    },
    fileName: whyWhyPdfName(machine.code ?? ref, date),
  };
}

/** `GET /api/v1/tickets/:id/why-why.pdf`: the server-image sheet (D25), guarded like the read (R3). */
async function sendWhyWhyPdf(
  deps: PdfDeps,
  request: FastifyRequest,
  reply: FastifyReply,
): Promise<void> {
  const auth = await requireAuth(deps.pool, request, reply);
  if (!auth) return;
  if (!canAnalytics(actorOf(auth))) {
    reply.code(403).send(apiError('forbidden', WHY_WHY_READ_REFUSAL));
    return;
  }
  const ticketId = (request.params as { id: string }).id;
  if (!isUuid(ticketId)) {
    reply.code(404).send(apiError('not_found', 'Unknown ticket'));
    return;
  }
  const found = await withTenant(deps.pool, auth.tenantId, (client) =>
    sheetOf(client, auth.tenantId, ticketId),
  );
  if (found.state === 'missing') {
    reply.code(404).send(apiError('not_found', 'Unknown ticket'));
    return;
  }
  if (found.state === 'not-breakdown') {
    reply.code(409).send(apiError('conflict', 'not-a-breakdown'));
    return;
  }
  if (found.state === 'no-record') {
    reply.code(409).send(apiError('conflict', 'This ticket has no saved Why-Why'));
    return;
  }
  const bytes = await renderOrBusy(reply, () =>
    renderPdf(renderWhyWhyHtml(found.input), deps.chromiumPath),
  );
  if (bytes) sendBytes(reply, bytes, found.fileName);
}

export function registerWhyWhyPdf(app: FastifyInstance, deps: PdfDeps): void {
  app.get('/api/v1/tickets/:id/why-why.pdf', (request, reply) =>
    sendWhyWhyPdf(deps, request, reply),
  );
}
