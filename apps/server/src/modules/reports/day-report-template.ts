/** The server-rendered day-report sheet: the person's day, their minutes and the pending queue. */
export function renderDayReportHtml(data: DayReportData): string {
  return `<!doctype html>
<html lang="${esc(data.tenant.language)}">
<head>
  <meta charset="utf-8" />
  <title>Day report ${esc(data.person.name)} ${esc(data.date)}</title>
  <style>${STYLES}</style>
</head>
<body>
${header(data)}
<section><h2>Jobs worked</h2>${jobsTable(data.jobs)}</section>
<section><h2>Pending at the end of the period (for the next shift)</h2>${pendingTable(
    data.pending,
  )}</section>
${footer(data)}
</body>
</html>`;
}
