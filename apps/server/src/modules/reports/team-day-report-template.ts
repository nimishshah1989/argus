import {
  STYLES,
  esc,
  formatDateTime,
  formatDay,
  formatWindow,
  jobsTable,
  minutesLabel,
  pendingTable,
  stat,
} from './day-report-template.js';
import type { TeamDayReportData, TeamMemberDay } from './team-report.js';

function header(data: TeamDayReportData): string {
  const tz = data.tenant.timeZone;
  return `<header>
    <div class="masthead">
      <div class="company">${esc(data.tenant.name)}</div>
      <h1>Team day report</h1>
      <div class="who">${esc(formatDay(data.window.start, tz))}</div>
      <div class="window">${esc(data.shift ? `Shift ${data.shift}` : 'Whole day')} · ${esc(formatWindow(data.window, tz))}</div>
    </div>
    <div class="stats">
      ${stat('People', String(data.people.length))}
      ${stat('Jobs', String(data.jobCount))}
      ${stat('Closed', String(data.closedCount))}
      ${stat('Team work time', minutesLabel(data.totalMinutes))}
      ${stat('Pending at end', String(data.pending.length))}
    </div>
  </header>`;
}

function summaryTable(data: TeamDayReportData): string {
  if (data.people.length === 0)
    return '<p class="empty">Nobody worked a ticket in this window.</p>';
  const rows = data.people.map(
    (row) => `<tr>
      <td>${esc(row.person.name)}</td>
      <td class="num">${row.jobs.length}</td>
      <td class="num">${row.closedCount}</td>
      <td class="num">${esc(minutesLabel(row.primaryMinutes))}</td>
      <td class="num">${esc(minutesLabel(row.supportMinutes))}</td>
      <td class="num">${esc(minutesLabel(row.totalMinutes))}</td>
    </tr>`,
  );
  const primary = data.people.reduce((total, row) => total + row.primaryMinutes, 0);
  const support = data.people.reduce((total, row) => total + row.supportMinutes, 0);
  return `<table>
    <thead><tr><th>Person</th><th class="num">Jobs</th><th class="num">Closed</th><th class="num">Primary</th><th class="num">Support</th><th class="num">Work</th></tr></thead>
    <tbody>${rows.join('')}
      <tr><td><strong>Team total</strong></td><td class="num"><strong>${data.jobCount}</strong></td><td class="num"><strong>${data.closedCount}</strong></td><td class="num"><strong>${esc(minutesLabel(primary))}</strong></td><td class="num"><strong>${esc(minutesLabel(support))}</strong></td><td class="num"><strong>${esc(minutesLabel(data.totalMinutes))}</strong></td></tr>
    </tbody>
  </table>`;
}

function personSection(row: TeamMemberDay): string {
  const split = `primary ${minutesLabel(row.primaryMinutes)}, support ${minutesLabel(row.supportMinutes)}`;
  return `<section><h2>${esc(row.person.name)} · ${esc(minutesLabel(row.totalMinutes))} (${esc(split)})</h2>${jobsTable(row.jobs)}</section>`;
}

/** The server-rendered team day sheet: who worked what in the window, each person's own minutes, and the pending queue. */
export function renderTeamDayReportHtml(data: TeamDayReportData): string {
  const generated = formatDateTime(data.generatedAt, data.tenant.timeZone);
  return `<!doctype html>
<html lang="${esc(data.tenant.language)}">
<head>
  <meta charset="utf-8" />
  <title>Team day report ${esc(data.date)}</title>
  <style>${STYLES}</style>
</head>
<body>
${header(data)}
<section><h2>Team</h2>${summaryTable(data)}</section>
${data.people.map(personSection).join('\n')}
<section><h2>Pending at the end of the period (for the next shift)</h2>${pendingTable(data.pending)}</section>
<footer>Generated by UPTIMO on ${esc(generated)} · Team · ${esc(data.date)}</footer>
</body>
</html>`;
}
